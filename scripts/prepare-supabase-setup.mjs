// Local SQL generation only. Never connects to Supabase or reads any API key.
import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const directory='supabase/migrations';
const files=(await readdir(directory)).filter(name=>/^\d+_.+\.sql$/.test(name)).sort();
const migrations=await Promise.all(files.map(async file=>{const sql=await readFile(`${directory}/${file}`,'utf8');return {file,version:file.split('_')[0],sql,hash:createHash('sha256').update(sql).digest('hex')};}));
const quote=value=>`'${value.replaceAll("'","''")}'`;
const values=migrations.map(m=>`(${quote(m.version)},${quote(m.file)},${quote(m.hash)},$forno_body_${m.version}$${m.sql}$forno_body_${m.version}$)`).join(',\n');
const output=`-- GENERATED by node scripts/prepare-supabase-setup.mjs; review before executing.
-- Target: SQL Editor of forno-pizza. The actual project ref is NOT known to this checkout.
-- Requires the user's approval after the read-only preflight. No reset, DROP or customer-order creation.
-- All schema changes are atomic; grants cannot be exposed between CREATE and REVOKE.
begin;
select pg_advisory_xact_lock(hashtextextended('forno-reviewed-setup',0));
do $forno_setup$
declare m record; known boolean; baseline boolean:=false; stored_hash text;
  existing_count integer;
begin
  -- Refuse an existing untracked application instead of guessing which migrations ran.
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select exists(select 1 from supabase_migrations.schema_migrations where version=$1)' into baseline using '202610280001';
  end if;
  if to_regclass('forno_private.manual_migrations') is not null then
    execute 'select exists(select 1 from forno_private.manual_migrations where version=$1)' into known using '202610280001';
    baseline:=baseline or known;
  end if;
  select count(*) into existing_count from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where c.relkind in ('r','p','v','m') and ((n.nspname='public' and c.relname in ('pizzas','services','pickup_slots','orders','order_items')) or n.nspname='forno_private');
  if existing_count>0 and not baseline then raise exception 'FORNO_BASELINE_UNTRACKED: existing objects without verified history. Stop and reconcile, do not rerun core migration.'; end if;
  if baseline and (to_regclass('public.pizzas') is null or to_regclass('public.services') is null or to_regclass('public.pickup_slots') is null or to_regclass('public.orders') is null or to_regclass('public.order_items') is null or to_regclass('forno_private.settings') is null or to_regclass('forno_private.request_limits') is null) then
    raise exception 'FORNO_HISTORY_SCHEMA_MISMATCH: migration history and application objects disagree';
  end if;
  create schema if not exists forno_private;
  create table if not exists forno_private.manual_migrations(version text primary key, filename text not null, sha256 text not null, applied_at timestamptz not null default now());
  alter table forno_private.manual_migrations enable row level security;
  revoke all on forno_private.manual_migrations from public,anon,authenticated,service_role;
  for m in select * from (values
${values}
  ) as migrations(version,filename,sha256,sql_body) order by version loop
    known:=false;stored_hash:=null;
    if to_regclass('supabase_migrations.schema_migrations') is not null then
      execute 'select exists(select 1 from supabase_migrations.schema_migrations where version=$1)' into known using m.version;
    end if;
    select sha256 into stored_hash from forno_private.manual_migrations where version=m.version;
    if stored_hash is not null and stored_hash<>m.sha256 then raise exception 'FORNO_MIGRATION_CHECKSUM_MISMATCH: %',m.filename; end if;
    known:=known or stored_hash is not null;
    if known then raise notice 'SKIP already recorded: %',m.filename;
    else
      execute m.sql_body;
      insert into forno_private.manual_migrations(version,filename,sha256) values(m.version,m.filename,m.sha256);
      raise notice 'APPLIED: %',m.filename;
    end if;
  end loop;
end $forno_setup$;
commit;
-- SQL Editor history is recorded in forno_private.manual_migrations.
-- It does NOT rewrite Supabase internal migration history. Reconcile CLI history before any future db push.
`;
await writeFile('supabase/setup/02-apply-reviewed.sql',output);
console.log(`Prepared ${migrations.length} migrations in supabase/setup/02-apply-reviewed.sql (no remote execution).`);

const catalogue=execFileSync(process.execPath,['scripts/prepare-order-data.mjs','catalogue'],{encoding:'utf8'});
const rows=catalogue.match(/ values\n([\s\S]+)\non conflict/)[1];
const template=await readFile('supabase/setup/postcheck-template.sql','utf8');
await writeFile('supabase/setup/03-verify-readonly.sql',template.replaceAll('TODO_CATALOGUE_VALUES',rows));
